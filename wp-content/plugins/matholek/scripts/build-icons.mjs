/**
 * Build the Solar Line Duotone icon classes for the Matholek theme.
 *
 * Source: the iconify-json solar package (CC BY 4.0). Add a name to ICONS, then
 * run `bun run icons`. Writes ../../themes/matholek/assets/css/icons.css
 * (`.mk-icon.mk-icon--<name>` mask classes); never edit that file by hand.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );
const solar = JSON.parse(
	readFileSync(
		resolve( root, 'node_modules/@iconify-json/solar/icons.json' ),
		'utf8'
	)
);

const ICONS = [
	'sun-2',
	'moon',
	'book-2',
	'book',
	'notebook',
	'text-square',
	'pen-new-square',
	'test-tube',
	'atom',
	'calculator',
	'square-academic-cap',
	'document-text',
];

const dataUri = ( body ) =>
	`url("data:image/svg+xml,${ encodeURIComponent(
		`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none">${ body.replaceAll(
			'currentColor',
			'#000'
		) }</svg>`
	) }")`;

let css =
	'/* Generated by plugins/matholek/scripts/build-icons.mjs (Solar Line Duotone, CC BY 4.0). Do not edit. */\n.mk-icon::before {\n\tcontent: "";\n\tdisplay: block;\n\twidth: 1.25rem;\n\theight: 1.25rem;\n\tbackground-color: currentColor;\n\t-webkit-mask: var(--mk-icon) center / contain no-repeat;\n\tmask: var(--mk-icon) center / contain no-repeat;\n}\n';

for ( const name of ICONS ) {
	const icon = solar.icons[ `${ name }-line-duotone` ];

	if ( ! icon ) {
		throw new Error( `Missing Solar icon: ${ name }-line-duotone` );
	}

	css += `.mk-icon--${ name } {\n\t--mk-icon: ${ dataUri( icon.body ) };\n}\n`;
}

const dir = resolve( root, '../../themes/matholek/assets/css' );
mkdirSync( dir, { recursive: true } );
writeFileSync( resolve( dir, 'icons.css' ), css );

// eslint-disable-next-line no-console
console.log( `Wrote ${ ICONS.length } icons.` );
